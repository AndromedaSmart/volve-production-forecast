def context() -> Dict:
    rows = pd.read_csv(REPORTS_DIR / "experiments_windows.csv")
    summ = pd.read_csv(REPORTS_DIR / "experiments_summary.csv")
    auto = pd.read_csv(REPORTS_DIR / "final_model_choice.csv")
    leak = pd.read_csv(REPORTS_DIR / "experiments_leakage.csv")
    met = pd.read_csv(REPORTS_DIR / "metrics_windows.csv")

    def rms(x):
        x = np.asarray(x, float)
        return float(np.sqrt(np.mean(x ** 2)))

    def get(fluid, mode, model, route="direct"):
        r = summ.loc[(summ.fluid == fluid) & (summ["mode"] == mode) & (summ.model == model) & (summ.route == route)]
        return float(r["RMS_WAPE"].iloc[0]) if len(r) else float("nan")

    ctx = {"rows": rows, "summ": summ, "auto": auto, "leak": leak, "met": met, "get": get}
    for fl in ("oil", "gas"):
        ctx[f"auto_{fl}"] = rms(auto.loc[auto.fluid == fl, "test_wape"])
        lv = leak.loc[(leak.fluid == fl) & (leak["mode"] == "volume")]
        ctx[f"leak_{fl}"] = rms(lv["leaky_test_wape"])
        ctx[f"honest_{fl}"] = rms(lv["honest_test_wape"])
        best = summ.loc[(summ.fluid == fl) & (summ["mode"] != "auto")].sort_values("RMS_WAPE").iloc[0]
        ctx[f"best_{fl}"] = best
    return ctx


