def _shade(cell, hex_color):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    tcPr.append(shd)


def add_table(doc, df: pd.DataFrame, widths=None, font=8.5):
    t = doc.add_table(rows=1, cols=len(df.columns))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, c in enumerate(df.columns):
        cell = t.rows[0].cells[i]
        cell.text = str(c)
        _shade(cell, "1F4E79")
        r = cell.paragraphs[0].runs[0]
        r.font.bold = True
        r.font.size = Pt(font)
        r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
    for _, row in df.iterrows():
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = f"{v:.1f}" if isinstance(v, (float, np.floating)) else str(v)
            cells[i].paragraphs[0].runs[0].font.size = Pt(font)
    if widths:
        t.autofit = False
        for i, w in enumerate(widths):
            t.columns[i].width = Cm(w)
        grid = t._tbl.tblGrid
        for i, gc in enumerate(grid.findall(qn("w:gridCol"))):
            gc.set(qn("w:w"), str(int(widths[i] * 567)))
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()
    return t


def comparison_df(ctx, fluid):
    s = ctx["summ"].loc[ctx["summ"].fluid == fluid].sort_values("RMS_WAPE")
    out = pd.DataFrame({
        "Модель": [MODEL_LABELS.get(m, m) for m in s.model],
        "Цель": [MODE_LABELS.get(m, m) for m in s["mode"]],
        "Газ": [ROUTE.get(r, r) if fluid == "gas" else "—" for r in s.route],
        **{f"Окно {w.variant}": s[f"w{w.variant}"].to_numpy() for w in WINDOWS},
        "RMS WAPE": s["RMS_WAPE"].to_numpy(),
    })
    return out


def auto_df(ctx):
    a = ctx["auto"]
    return pd.DataFrame({
        "Окно": a.variant, "Флюид": a.fluid.map({"oil": "нефть", "gas": "газ"}),
        "Модель": [MODEL_LABELS.get(m, m) for m in a.model], "Цель": [MODE_LABELS.get(m, m) for m in a["mode"]],
        "Газ": [ROUTE.get(r, r) if f == "gas" else "—" for r, f in zip(a.route, a.fluid)],
        "Параметры": a.params, "WAPE валид., %": a.inner_wape, "WAPE тест, %": a.test_wape,
    })


