def build_figures_md(ctx, figs):
    lines = ["# Альбом графиков", "",
             f"Все рисунки решения кейса Volve (версия 2). Нумерация G1–G{len(figs)}, файлы в `figures/`. Ниже графиков — легенда.", ""]
    section = None
    for f in figs:
        if f["section"] != section:
            section = f["section"]
            lines += [f"## {section}", ""]
        lines += [f"### {f['id']}. {f['title']}", "", f"![{f['id']}]({f['file']})", "", f"**Подпись.** {f['caption']}", ""]
    lines += ["## Легенда", ""]
    for f in figs:
        lines += [f"### {f['id']}", ""]
        for k, lab in (("title", "Название"), ("file", "Файл"), ("why", "Обоснование"), ("desc", "Описание")):
            if f[k]:
                val = f"`{f[k]}`" if k == "file" else f[k]
                lines += [f"- **{lab}.** {val}"]
        lines += [""]
    (ROOT / "FIGURES.md").write_text("\n".join(lines), encoding="utf-8")


